import { createHash } from "node:crypto";
import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { join, relative, resolve } from "node:path";

const root = process.cwd();
const output = resolve(root, "src/generated-facts.js");
const check = process.argv.includes("--check");
const require = createRequire(import.meta.url);

function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, canonicalize(value[key])]),
    );
  }
  return value;
}

function digest(value) {
  const bytes = `${JSON.stringify(canonicalize(value))}\n`;
  return `sha256:${createHash("sha256").update(bytes).digest("hex")}`;
}

function filesBelow(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const child = join(directory, entry.name);
    if (entry.isDirectory()) return filesBelow(child);
    return child === output ? [] : [child];
  });
}

const packagePath = require.resolve("@kungfu-tech/kfd/package.json");
const manifestPath = require.resolve(
  "@kungfu-tech/kfd/protocols/agent-hub/manifest.json",
);
const kfdPackage = JSON.parse(readFileSync(packagePath, "utf8"));
const manifestBytes = readFileSync(manifestPath);
const manifest = JSON.parse(manifestBytes);
const productPackage = JSON.parse(
  readFileSync(resolve(root, "package.json"), "utf8"),
);

const files = [...filesBelow(resolve(root, "src")), resolve(root, "package.json")]
  .filter((path) => statSync(path).isFile())
  .map((path) => ({
    path: relative(root, path).replaceAll("\\", "/"),
    sha256: createHash("sha256").update(readFileSync(path)).digest("hex"),
  }))
  .sort((left, right) => left.path.localeCompare(right.path));
const artifactBody = {
  contract: "agent-hub-demo.adapter-artifact/v1",
  entry: "src/adapter.js",
  files,
};
const artifact = { ...artifactBody, root: digest(artifactBody) };
const kfd = {
  package: kfdPackage.name,
  packageVersion: kfdPackage.version,
  profileId: manifest.profile.id,
  profileVersion: manifest.profile.version,
  manifest,
  manifestDigest: `sha256:${createHash("sha256").update(manifestBytes).digest("hex")}`,
  source: "public-npm-build-input",
};
const generated = [
  "// Generated by scripts/generate-embedded-facts.mjs. Do not edit.",
  `export const PRODUCT_VERSION = ${JSON.stringify(productPackage.version)};`,
  `export const EMBEDDED_KFD = Object.freeze(${JSON.stringify(kfd, null, 2)});`,
  `export const EMBEDDED_ADAPTER_ARTIFACT = Object.freeze(${JSON.stringify(artifact, null, 2)});`,
  "",
].join("\n");

if (check) {
  const current = existsSync(output) ? readFileSync(output, "utf8") : "";
  if (current !== generated) {
    throw new Error(
      "src/generated-facts.js is stale; run npm run generate:embedded",
    );
  }
} else {
  writeFileSync(output, generated);
  process.stdout.write(
    `${JSON.stringify({ status: "generated", output: relative(root, output), adapterRoot: artifact.root })}\n`,
  );
}
